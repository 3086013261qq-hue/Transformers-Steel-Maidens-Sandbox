"""Deterministic local bundling, no downloaded build dependencies."""
from pathlib import Path
import json,re,hashlib
BASE=Path(__file__).resolve().parent
ROOT=BASE.parents[1]
parts=[]
for name in ['causality.mjs','player.mjs','runtime.mjs']:
    s=(BASE/'src'/name).read_text()
    s=re.sub(r'^import .*;\n','',s,flags=re.M)
    s=re.sub(r'\bexport (?=(?:function|const)\b)','',s)
    parts.append(s)
manifest=json.loads((ROOT/'mvu/music-manifest.v1.json').read_text())
media=json.loads((BASE/'src/media.json').read_text())
css=(BASE/'src/styles.css').read_text()
bundle='// Generated by build.py. Fullstack MVU runtime adaptation; do not edit dist.\n(() => {\n"use strict";\n'+'\n'.join(parts)
bundle+='\n$(() => { boot({ window, getChatMessages, getLastMessageId, eventOn,\n'
bundle+="  eventRemoveListener: typeof eventRemoveListener === 'function' ? eventRemoveListener : undefined,\n"
bundle+="  tavern_events: typeof tavern_events === 'object' ? tavern_events : {},\n"
bundle+="  Mvu: typeof Mvu === 'object' ? Mvu : undefined }, "
bundle+=json.dumps(manifest,ensure_ascii=False)+', '+json.dumps(css)+', '+json.dumps(media)+'); });\n})();\n'
(BASE/'dist/steel-maidens-mvu.js').write_text(bundle)
print('dist SHA256',hashlib.sha256(bundle.encode()).hexdigest())
